// Flatten lessons into per-lesson word arrays
function getLessonWords(level, lesson) {
  const data = VOCAB[level]?.[lesson];
  if (!data) return [];
  const words = [];
  data.sections.forEach(section => {
    section.words.forEach(w => {
      words.push({ ...w, cat: section.cat });
    });
  });
  return words;
}

function getLessonTitle(level, lesson) {
  return VOCAB[level]?.[lesson]?.title || `Lesson ${lesson}`;
}

function getLessons(level) {
  return Object.keys(VOCAB[level] || {}).map(Number).sort((a, b) => a - b);
}
